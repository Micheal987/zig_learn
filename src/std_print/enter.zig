// std.debug.print("格式化字串", .{ 變數1, 變數2, ... });
//核心死守原則：最後面那個點開頭的 .{}（元組）永遠不能省略！就算不印變數，也必須寫成空元組 .{}
// ====================================================================
// 🎯 ZIG 常用列印占位符快速查閱表 (Print Specifiers Cheat Sheet)
// ====================================================================
// 語法  | 適用類型             | 範例程式碼                 | 輸出結果
// -----+----------------------+--------------------------+-----------------------
// {}   | 自動推導 (最省心)     | print("{}", .{100});     | 100
// {s}  | 字串 / 字元切片      | print("{s}", .{"Zig"});  | Zig
// {c}  | 單個字元 (ASCII)     | print("{c}", .{'A'});    | A
// {d}  | 十進位整數/浮點數    | print("{d}", .{3.14});   | 3.14
// {x}  | 十六進位 (小寫)      | print("{x}", .{255});    | ff
// {X}  | 十六進位 (大寫)      | print("{X}", .{255});    | FF
// {b}  | 二進位               | print("{b}", .{5});      | 101
// {*}  | 指標 (印記憶體地址)   | print("{*}", .{&x});     | i32@7ffeefbff5a8
// {any}| 任意複雜結構 (萬能印) | print("{any}", .{array});| [5]i32{ 1, 2, 3, 4, 5 }
// ====================================================================
// 💡 死守原則：不論有沒有帶變數，最後面的元組 `.{}` 永遠都不能省略！

const std = @import("std");

pub fn main() void {
    // 這裡放您的程式碼
    std.debug.print("秘笈已成功加入註釋！\n", .{});
}
